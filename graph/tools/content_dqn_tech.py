def build():
    # 校验：毛的术语必须在术语表里
    missing = sorted({t for st in STATIONS for (_, _, fur) in st[2] for t in fur
                      if t not in GLOSSARY})
    if missing:
        raise SystemExit("术语表缺词：%s" % missing)

    stations = []
    for label, color, legs in STATIONS:
        out_legs = []
        for name, explain, fur in legs:
            details = ["【详解】" + explain]
            for term in fur:
                details.append("【术语·%s】%s" % (term, GLOSSARY[term]))
            out_legs.append({"t": name, "d": details})
        stations.append({"label": label, "color": color, "legs": out_legs})

    data = {
        "id": "s.dqn.tech",
        "label": "魔方 DQN 技术蜈蚣",
        "sub": "核心术语 + 数据流 12 站 · 脑图模式为默认视图",
        "color": "#0F766E",
        "source": "一条数据流 + 各站技术点 + 核心术语大白话",
        "flow": FLOW,
        "core_terms": [{"t": a, "d": b} for a, b in CORE_TERMS],
        "facts": [{"t": a, "d": b} for a, b in FACTS],
        "stations": stations,
    }
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(
        json.dumps(data, ensure_ascii=False, indent=1))
    n_legs = sum(len(s["legs"]) for s in stations)
    n_fur = sum(len(l["d"]) - 1 for s in stations for l in s["legs"])
    n_cards = sum(len(l["d"]) for s in stations for l in s["legs"])
    print("  stations=%d  legs=%d  详解=%d  毛=%d  说明卡合计=%d  flow=%d  术语表=%d"
          % (len(stations), n_legs, n_legs, n_fur, n_cards, len(FLOW), len(GLOSSARY)))
    print("  core_terms=%d  facts=%d" % (len(CORE_TERMS), len(FACTS)))
    assert len(FLOW) == len(stations) - 1, "FLOW 数量必须 = 站数 - 1"


if __name__ == "__main__":
    build()

def build():
    stations = []
    for label, color, legs in STATIONS:
        stations.append({
            "label": label,
            "color": color,
            "legs": [{"t": name, "d": [desc]} for name, desc in legs],
        })
    data = {
        "id": "s.dqn.tech",
        "label": "魔方 DQN 技术蜈蚣",
        "sub": "12 站主干 · 技术腿垂直挂载",
        "color": "#0F766E",
        "source": "由技术蜈蚣附录提炼：一条数据流 + 各站技术点",
        "flow": FLOW,
        "stations": stations,
    }
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(
        json.dumps(data, ensure_ascii=False, indent=1))
    n_legs = sum(len(s["legs"]) for s in stations)
    n_desc = sum(len(l["d"]) for s in stations for l in s["legs"])
    print("  stations=%d  legs=%d  desc=%d  flow=%d"
          % (len(stations), n_legs, n_desc, len(FLOW)))
    assert len(FLOW) == len(stations) - 1, "FLOW 数量必须 = 站数 - 1"


if __name__ == "__main__":
    build()
